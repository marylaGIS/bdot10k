# This loads your .ui file so that PyQt can populate your plugin with the elements from Qt Designer
FORM_CLASS, _ = uic.loadUiType(os.path.join(
    os.path.dirname(__file__), 'bdot10k_dialog_by_layer.ui'))


class BDOT10kDialogByLayer(QDialog, FORM_CLASS, DialogMixin):
    def __init__(self, parent=None):
        """Constructor."""
        super().__init__(parent)
        # Set up the user interface from Designer through FORM_CLASS.
        # After self.setupUi() you can access any designer object by doing
        # self.<objectname>, and you can use autoconnect slots - see
        # http://qt-project.org/doc/qt-4.8/designer-using-a-ui-file.html
        # #widgets-and-dialogs-with-auto-connect
        self.setupUi(self)

        self.plugin_dir = os.path.dirname(__file__)
        self.powiatyTerytByLayer = []
        self.taskManager = QgsApplication.taskManager()

        # set filters for the map layer combo box - only vector layers
        self.mcbLayer.setFilters(QgsMapLayerProxyModel.PointLayer |
                                            QgsMapLayerProxyModel.LineLayer |
                                            QgsMapLayerProxyModel.PolygonLayer)
        self.txt.clear()

    def on_mcbLayer_layerChanged(self):
        self.txt.clear()
        self.powiatyTerytByLayer.clear()

        if self.mcbLayer.currentIndex() != -1:
            selectionLayer = self.mcbLayer.currentLayer()
        else:
            return

        try:
            QApplication.setOverrideCursor(QCursor(Qt.BusyCursor))

            if selectionLayer.featureCount() == 0:
                QApplication.restoreOverrideCursor()
                self.txt.append(f'Liczba powiatów do pobrania: {len(self.powiatyTerytByLayer)}')
                QMessageBox.warning(self, "Uwaga", "Wybrana warstwa nie zawiera obiektów.")
            else:
                powiatyLayer = QgsVectorLayer(
                    os.path.join(self.plugin_dir, 'powiaty.geojson'),
                    'powiaty',
                    'ogr'
                )

                powiatySelected = processing.run(
                    "native:selectbylocation",
                    {'INPUT': powiatyLayer,
                    'PREDICATE': [0],
                    'INTERSECT': selectionLayer,
                    'METHOD': 0}
                )['OUTPUT'].selectedFeatures()

                powiatyTxt = "Powiaty: "

                if powiatySelected:
                    for feature in powiatySelected:
                        self.powiatyTerytByLayer.append(feature["teryt"])
                        powiatyTxt += f'{feature["teryt"]} {feature["nazwa"]}, '

                    self.txt.append(f'Liczba powiatów do pobrania: {len(self.powiatyTerytByLayer)}')
                    self.txt.append(powiatyTxt)
                else:
                    self.txt.append(f'Liczba powiatów do pobrania: {len(self.powiatyTerytByLayer)}')
                    QMessageBox.warning(self, "Uwaga", "Wybrana warstwa nie znajduje się na terenie żadnego powiatu.")
        except Exception as e:
            QApplication.restoreOverrideCursor()
            QgsMessageLog.logMessage(
                f'Wystąpił błąd podczas selekcji powiatów. Treść błędu: {e}',
                'BDOT10k',
                Qgis.MessageLevel.Critical
            )
        finally:
            QApplication.restoreOverrideCursor()

        return self.powiatyTerytByLayer

    @pyqtSlot()
    def on_btnDwnl_clicked(self):
        if not self.powiatyTerytByLayer:
            QMessageBox.critical(self, "Błąd", "Brak powiatów do pobrania.")
        else:
            downloadPath = self.dwnlPath.filePath()

            oldSchema, bdot10kDataFormat = self.get_bdot10k_data_options()

            if check_dwnl_path(downloadPath):

                self.btnDwnl.setEnabled(False)

                QgsMessageLog.logMessage(f'Lokalizacja pobierania: {downloadPath}', 'BDOT10k', level=Qgis.MessageLevel.Info)
                QgsMessageLog.logMessage('Pobieranie paczek dla powiatów: ' + str(sorted(self.powiatyTerytByLayer)), 'BDOT10k', level=Qgis.MessageLevel.Info)

                task = DownloadBdotTask(
                    description="Pobieranie paczek BDOT10k",
                    downloadPath=downloadPath,
                    oldSchema=oldSchema,
                    bdot10kDataFormat=bdot10kDataFormat,
                    powiatyTerytList=self.powiatyTerytByLayer,
                    iface=iface
                )

                self.taskManager.addTask(task)
                self.taskManager.addTask(task)
                self.taskId = self.taskManager.taskId(task)
                self.taskManager.statusChanged.connect(self.enable_btn_dwnl)
